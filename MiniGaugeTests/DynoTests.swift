    func testPullMatchesTheWebPage() throws {
        let rows = DynoMath.parseCSV(Self.csv)
        XCTAssertEqual(rows.count, 100)
        guard case .success(let r) = DynoMath.compute(rows, DynoSettings()) else { return XCTFail("no result") }
        XCTAssertEqual(r.gear, 3)
        XCTAssertEqual(r.speedSource, "front wheel speeds")
        XCTAssertEqual(r.peakHp, 156, accuracy: 1.0)
        XCTAssertEqual(r.peakHpRpm, 5762, accuracy: 60)
        XCTAssertTrue(r.peakTq > 100 && r.peakTq < 200)
    }

    func testTimesNeedAStandingStart() {
        let rows = DynoMath.parseCSV(Self.csv)
        let t = DynoMath.times(rows)
        XCTAssertFalse(t.fromStop)
        XCTAssertTrue(t.rows.contains { $0.name == "30-70 mph" && $0.seconds != nil })
        XCTAssertFalse(t.rows.contains { $0.name.hasPrefix("0-") })
    }

    func testFailures() {
        XCTAssertEqual(DynoMath.compute([], DynoSettings()), .failure(.tooFew))
    }
